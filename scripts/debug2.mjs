import puppeteer from "puppeteer-core";
const browser = await puppeteer.launch({ executablePath: "/usr/bin/chromium", headless: "new", args: ["--no-sandbox", "--disable-dev-shm-usage"] });
const page = await browser.newPage();
page.on("console", (m) => console.log("CONSOLE:", m.text()));
await page.goto("http://localhost:4173/", { waitUntil: "networkidle0" });
await page.evaluate(() => { const el = [...document.querySelectorAll("button")].find((b) => b.textContent.includes("Configuración")); el.click(); });
await page.waitForSelector(".freeze-select");
console.log("before:", await page.evaluate(() => document.querySelector(".freeze-select").value));
await page.select(".freeze-select", "1");
console.log("immediately:", await page.evaluate(() => document.querySelector(".freeze-select").value));
await new Promise((r) => setTimeout(r, 2000));
console.log("after 2s:", await page.evaluate(() => document.querySelector(".freeze-select").value));
await browser.close();
